import classNames from '@/utils/classNames'

/**
 * 골드포스 표시 칩 (FC-058 재작업 2차) — `design-system.md §5.12` 접근성 절.
 *
 * ══════════════════════════════════════════════════════════════════════════════
 * ★★ **아웃라인을 전부 제거해도 정보 손실이 없어야 한다** — §5.12 의 합격선이다.
 *    이 칩이 그 합격선을 지키는 장치다.
 * ══════════════════════════════════════════════════════════════════════════════
 * 금색 아웃라인은 §5.12 가 명시하듯 **보조 신호**다. 정보를 나르는 것은 이 칩의 **글자**다.
 * 사용자가 속성·종류·레벨 태그를 지우라 했으므로 골드포스마저 색에만 실리면 그 순간
 * **색 단독 정보 전달**(WCAG 1.4.1)이 된다. 색각 이상·흑백 출력·저대비 환경 어디서든
 * "골드포스"라는 낱말이 남는다.
 *
 * 생김새는 §5.12 가 규정한 그대로다 — **흰 칩 + 금 도트 + 텍스트**.
 * 도트의 `#DFC447` 은 아웃라인 밝은 겹 그라데이션의 중간 스톱이라 **새 색이 아니다**
 * (같은 램프에서 뽑았다 — 세 번째 금색을 만들면 램프가 생긴다).
 *
 * ★ **활성일 때만 렌더된다.** 비활성 카드에 "골드포스 없음"을 붙이면 대다수 카드가
 *   부정형 라벨을 달게 되어 소음이 된다 — 없는 것은 말하지 않는 게 기본값이다.
 *
 * ★ **위치는 카드 본문 한 곳으로 통일했다.** §5.12 는 "슬롯 좌상단"을 적었으나 그 자리는
 *   행목록의 1배 아트(**50px 폭**)에서 칩이 아트를 덮는다. 홈은 1·2·3배가 공존하므로
 *   자리를 크기마다 바꾸면 같은 정보가 화면마다 다른 데서 나온다(product.md 가 금하는
 *   *"inconsistent component vocabulary"*). **문서의 의도(텍스트 배지가 존재한다)는
 *   충족하고 배치만 일관성 쪽으로 골랐다** — 편차로 보고한다.
 */

interface GoldforceChipProps {
    className?: string
}

const GoldforceChip = ({ className }: GoldforceChipProps) => {
    return (
        <span
            data-testid="goldforce-chip"
            className={classNames(
                'inline-flex items-center gap-1.5 rounded-md border px-1.5 py-0.5 text-xs font-bold leading-none',
                // 흰 칩 + near-black 라벨(§5.12). 다크에서는 면을 낮춰 같은 위계를 유지한다.
                'border-gray-200 bg-white text-gray-900',
                'dark:border-gray-600 dark:bg-gray-900 dark:text-gray-100',
                className,
            )}
        >
            {/*
             * 금 도트 — 값은 전부 §5.12 실측 램프에서 가져왔다(새 색 창작 없음).
             *
             * ★ **라이트와 다크가 램프의 다른 지점을 쓴다.** 처음엔 양쪽 모두 밝은 금
             *   `#DFC447` 을 썼는데 **흰 칩 위에서 1.73** 으로 거의 보이지 않았다(실측).
             *   그래서 라이트는 **베벨 층의 어두운 금 `#8B6100`(5.52)**, 다크는 밝은 금
             *   `#DFC447`(10.35) 로 나눴다 — 아웃라인이 2겹을 갖는 것과 같은 이유이고,
             *   두 값 다 원본 자산에서 나온 것이라 램프가 늘어나지 않는다.
             *
             * ★ 엄밀히는 **1.4.11 대상이 아니다** — 옆의 "골드포스" 글자가 정보를 나르므로
             *   도트는 "내용 이해에 필요한 그래픽"이 아니다. 그래도 **거의 안 보이는 장식은
             *   장식으로서도 실패**라 고쳤다.
             */}
            <span
                aria-hidden="true"
                className="size-1.5 shrink-0 rounded-full bg-[#8B6100] dark:bg-[#DFC447]"
            />
            골드포스
        </span>
    )
}

export default GoldforceChip
