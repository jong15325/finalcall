/** 레벨 → 최소 요구 채널 등급 표시. 표시 전용(계약 아님). */
export function channelLimitOf(level: number): string {
    if (!Number.isFinite(level) || level <= 0) return '제한 없음'
    if (level <= 3) return '초보채널 이상'
    if (level <= 7) return '고수채널 이상'
    return '마스터채널 이상'
}
